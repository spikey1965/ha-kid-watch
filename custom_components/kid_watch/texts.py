def _lang(hass: HomeAssistant) -> str:
    code = str(hass.config.language or "en").lower().replace("_", "-")
    if code in TEXTS:
        return code
    return code.split("-")[0] if code.split("-")[0] in TEXTS else "en"


def text(hass: HomeAssistant, key: str, **kw) -> str:
    words = TEXTS[_lang(hass)]
    return (words[key] if key in words else TEXTS["en"][key]).format(**kw)


def devices(hass: HomeAssistant, n: int) -> str:
    """'1 device' / '3 devices', with Polish's extra plural form."""
    lang = _lang(hass)
    if n == 1:
        form = "dev_one"
    elif lang == "pl" and 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        form = "dev_few"
    else:
        form = "dev_other"
    return text(hass, form, n=n)
